"""主人明确指使的判定：谁说「你去搜一下 X」，这事就不归软限管（T-0042 补丁）。

为什么需要这一层
----------------
``[self_action]`` 的四道闸门（``enabled`` / 静默时段 / ``daily_cap`` / 渴望阈值）
防的都是**她自己想动手**。主人已经把话说出来了，那就不是"她想"，是"他让她"。
把主人的明确指令卡在"你还不够想"上，是纯损失：体验上像没听见，语义上也错位。

判定依据只有一条：**主人的原话**。模型在动作参数里自报的 ``explicit`` /
``user_requested`` 之类字段一律不看 —— 否则软限就成了模型自己能开的门，等于没有。
调用方传进来的文本必须已经是"真实入站消息"那一路（``runtime`` 里
``sticker_user_text = "" if ephemeral_input else text``，自生成回合是空串），
所以"她自己决定去搜"这句永远不会走到这里，也就永远拿不到豁免。

这是启发式，不是分类器
----------------------
各类动作各自一组正则，先剔除被否定的片段（「别搜了」「不用查空间」「不要画」「别翻聊天记录」），
再匹配「指令词 + 动作词 + 目标词」。设计上刻意让它**宁可漏判**：

* 漏判 → 回落到旧的阈值路径，行为和补丁前完全一样，不会出错；
* 误判 → 一次多出来的搜索/生图，有 ``policy.validate`` 的每工具每轮上限兜着。

对 ``talk_to``（T-0082）这套权衡更重：豁免在那儿不是「绕过软限」而是
「唯一的门」（没有主人原话整个动作直接拒绝），所以它的前缀不含 ``^``/标点、
动词带前后断言，把「我跟你说」「跟他聊天很开心」这类陈述挡在外面。

已知会漏（写在这里，免得以后当成 bug 修）：整句只有一个链接让你看、只说
「那个视频」而不带动作词、方言/外语表达。遇到就补一条正例，别改成 ``.*``
跨句匹配——那会把「今天看了一天视频好累」这种感慨也算成指令。
"""

from __future__ import annotations

import re
from typing import Any

__all__ = ["EXEMPT_TOOLS", "explicit_request"]

#: 动词与目标词之间允许的最大间隔。用有界字符类而不是 ``.*``：跨句匹配会让
#: 「别管了。我刚搜了半天记忆」这类句子漏过否定剔除后被判成指令。
_GAP = r"[^。！？!?\n]{0,16}"

#: 否定词 + 动作词：「别搜了」「不用查空间」「不要画」「算了别找了」。
#: 先整段删掉，再做正例匹配，比在每条正则里都加后行断言好维护。
_NEGATED = re.compile(
    r"(?:别|不要|不用|甭|无需|不必|算了|省得|免得)"
    r"[^。！？!?\n]{0,8}"
    r"(?:搜|查|找|看|翻|画|生成|拍|做)"
)

#: 「帮我」「你去」「能不能」这类祈使前缀。放在动作词前面要求出现，
#: 是为了把「我找了半天记忆里都没有」这种陈述句挡在外面。
_DIRECTIVE = (
    r"(?:^|[，,、。！？!?\s]|帮我|帮忙|给我|替我|你去|去|请|麻烦|"
    r"能不能|可不可以|可以|赶紧|快点|快|顺便|再|你)"
)

#: talk_to（T-0082）用的祈使前缀：只收真祈使词，**不带** ``^``/标点/空白——
#: 「跟他聊天很开心」「，跟同事聊天很开心」这类以对象开头的陈述句、逗号后半截
#: 的感慨，都落不进来（对 talk_to 误判的代价是多发一条消息，收得比别的工具紧）。
_TALK_DIRECTIVE = (
    r"(?:帮我|帮忙|给我|替我|你去|去|请|麻烦|"
    r"能不能|可不可以|可以|赶紧|快点|快|顺便|再|你)"
)

#: talk_to 的说话动词。前一行断言排掉「跟(我|你)紧贴动词」的形状——那是对
#: 当前对话的人说话（「我跟你说」「你跟我说」），不是让她去找第三人；
#: 「去跟你妈说一声」仍然命中（动词前是「妈」）。后一行断言排掉过去时追问
#: （「跟他说了没」「聊过了」）。
_TALK_VERB = r"(?<![我你])(?:打个招呼|打招呼|聊|说|讲|谈|问|唠|转告|捎|传|带|提)(?!了|过)"

#: talk_to 的间隔词与动词之间不允许出现「我」——「你再跟我说说」「你跟我说说」
#: 的对象是当前对话的人（间隔里躺着「我」），不是让她去找第三人；正常指令的
#: 间隔只有对象名字（「去跟杨老师说…」）。「你」不排除：「你妈/你姐」是对象名。
_TALK_GAP = r"(?:[^。！？!?\n我]){0,16}"


def _rule(*parts: str, flags: int = 0) -> re.Pattern[str]:
    """``_rule(a, b, c)`` → ``a + b + _GAP + c``(between b and c)."""
    head = "".join(parts[:-1])
    return re.compile(head + _GAP + parts[-1], flags)


#: 每个工具一组合法说法。**按工具分开**是关键：问「搜一下视频」不能给
#: ``make_photo`` 发豁免，否则四道闸门会被一个泛化的关键词一起打穿。
_EXEMPT_RULES: dict[str, tuple[re.Pattern[str], ...]] = {
    "search_memory": (
        _rule(_DIRECTIVE, r"(?:搜|查|找|翻|回忆)", r"(?:记忆|记录|以前|之前|上次|上回|说过|聊过|旧账|老账)"),
        _rule(r"", r"(?:搜|查|找|翻|回忆)(?:一下|一遍|一次|下|个)", r"(?:记忆|记录|以前|之前|上次|上回|说过|聊过)"),
        # 「你还记得…吗」「记不记得」本身就是让我去翻记忆。
        re.compile(r"(?:记不记得|还记得|想不想得起)"),
    ),
    "read_qzone": (
        _rule(_DIRECTIVE, r"(?:看|读|刷|查|翻|打开|扫)", r"(?:空间|动态|说说|朋友圈)"),
        _rule(r"", r"(?:空间|动态|说说)(?:里|上)?", r"(?:看看|看一下|瞅瞅|翻翻|刷一下|读一下|有啥|有什么)"),
        _rule(r"", r"(?:去|看看|瞅瞅|刷刷)(?:一下|一?眼)?", r"(?:空间|动态|说说)"),
    ),
    "make_photo": (
        _rule(_DIRECTIVE, r"(?:画|生成|做|拍|渲染|来|出)", r"(?:图|照片|画|壁纸|头像|表情|海报|插画)"),
        _rule(r"", r"(?:画|生成|渲染|来)(?:一?张|一?个|一?幅|一?下)", r""),
        _rule(r"", r"(?:画|生成|渲染)(?:一?张|一?个|一?幅)?", r"(?:图|照片|壁纸|头像|表情|海报)"),
    ),
    "search_videos": (
        _rule(_DIRECTIVE, r"(?:搜|找|查|看|刷)", r"(?:视频|b站|bilibili|小破站|番剧|vlog)"),
        _rule(r"", r"(?:搜|找|查)(?:一下|一遍|一次|下|个|点)", r"(?:视频|b站|bilibili|小破站|番剧)"),
        _rule(
            r"(?:b站|bilibili|小破站)",
            r"(?:上|里)?",
            r"(?:搜|找|看看|看一下|有啥|有什么|逛逛|溜达|刷|翻翻|翻)",
            flags=re.IGNORECASE,
        ),
    ),
    # T-0072: 读对话。「群里都在聊什么」这类裸问句也算指令——问出口就是想让人去读。
    # 注意和 read_qzone 分开：这里只认群/聊天记录/「谁说了什么」，不认空间动态。
    # T-0081: 补私聊口语面——「看看妈妈的私聊」「可以看到妈妈的对话了吗」
    # 「QQ号xxx你看看有没有」。模型两次零调用 read_chat，说明口语说法必须
    # 显式进正则，不能指望泛化。
    "read_chat": (
        # 看看/翻翻/查一下 + 聊天记录/群消息/私聊/对话
        _rule(
            _DIRECTIVE,
            r"(?:看|读|翻|查|瞅|扒)(?:一?下|一?遍|一?眼)?",
            r"(?:群里?(?:的)?(?:消息|聊天记录)|聊天记录|群消息|私聊|对话)",
        ),
        # 群(里) + 说了什么 / 在聊什么 / 都聊啥
        _rule(r"", r"群里?", r"(?:说了?|聊了?|在聊)(?:什么|啥)"),
        # 看看 + (某人)说了什么
        _rule(r"", r"(?:看看|瞅瞅|瞧瞧)", r"说了?(?:什么|啥)"),
        # 能(可以)看 + (xx的)私聊/对话/聊天记录。「看不到/看不见」是否定能力
        # 不是指令，用先行否定剔掉。
        _rule(
            r"",
            r"[能可](?:以)?看(?!不到|不见)",
            r"(?:私聊|对话|聊天记录|聊天消息|(?:说了?|聊了?)(?:什么|啥))",
        ),
        # 裸 QQ 号 + 看看类动词（两个顺序都认）：号码本身就是指名道姓。
        re.compile(
            r"\d{5,}[^。！？!?\n]{0,16}(?:你)?(?:看看|瞅瞅|瞧瞧|翻翻|看一下|查一下|翻一下)"
            r"|(?:看看|瞅瞅|瞧瞧|翻翻|看一下|查一下|翻一下)[^。！？!?\n]{0,16}\d{5,}"
        ),
    ),
    # T-0074: 看一条具体的视频。目标必须是「有指代的」：这个视频/这个BV号/这个链接
    # 或者裸 BV 号/站内链接本身——「看了一天视频」这类没有指代的陈述句
    # （动词前不是祈使前缀、宾语没有这个/那个）落不进来，宁漏勿误。
    "watch_video": (
        # 看看/瞅瞅/刷一下 + 这个视频/这个BV号/这个链接
        _rule(
            _DIRECTIVE,
            r"(?:看|瞅|瞧|刷)(?:一?下|一?眼|一?遍|一?个)?",
            r"(?:这|那)(?:个|条)?(?:视频|影片|片子|BV号?|av[0-9]{4,}|b23\.tv|bilibili\.com)",
        ),
        _rule(_DIRECTIVE, r"(?:看|瞅|瞧)(?:一?下|一?眼)?", r"(?:链接|BV[0-9A-Za-z]{6,12})"),
        # BV号/链接在前 + 看看在后：「BV17x411w7KC 帮我看看」「b23.tv/xxx 看看」
        _rule(
            r"",
            r"(?:BV[0-9A-Za-z]{8,12}|av[0-9]{6,}|b23\.tv/\S*|bilibili\.com/video/\S*|BV号)",
            r"(?:看看|看一下|瞅瞅|瞧瞧)",
        ),
        # 这个视频在前 + 看看在后：「这个视频帮我看看」
        _rule(r"", r"(?:这|那)(?:个|条)?(?:视频|影片|片子)", r"(?:看看|看一下|瞅瞅|瞧瞧)"),
    ),
    # T-0082: 让她去跟某个**指名道姓的人**说话。这里的豁免不是「绕过软限」
    # 而是「唯一的门」：没有主人原话整个动作就被运行时拒掉
    # （needs_owner_instruction），所以正例必须稳稳接住口语说法，反例必须把
    # 「我跟你说」这类陈述挡在外面（宁漏勿误在这里更重——误判的代价是多发
    # 一条消息）。形状：祈使前缀 + 跟/和/与/同（或 给）+ 对象 + 说话动词。
    # 已知会漏（刻意收窄）：「跟妈妈说一声」（无前缀的裸祈使）、「帮我问下
    # 妈妈」（无连接词）、「不要跟他说，跟妈妈说」（前半否定后半指令的混合句）。
    "talk_to": (
        # 手工拼而不是 _rule：这条的间隔要用 _TALK_GAP（不含「我」）。
        re.compile(_TALK_DIRECTIVE + r"[跟和与同]" + _TALK_GAP + _TALK_VERB),
        # 「帮我给妈妈带个话」「帮我给我姐带个话」——给 + 对象 + 传话类动词。
        # 这条用公共 _GAP：动词类已经很窄（传话/说一声/转告），而且「给我姐」
        # 这种对象名本身就带「我」，间隔排除「我」会把正例打没。
        re.compile(
            _TALK_DIRECTIVE
            + r"给"
            + _GAP
            + r"(?<![我你])(?:带个话|捎个话|传个话|带话|捎话|传话|说一声|转告)(?!了|过)"
        ),
    ),
}

#: 一份方便外部遍历/断言的键集合（这里不 import ``SELF_ACTION_TOOLS``，避免
#: ``service`` ↔ ``explicit`` 的循环引用）。T-0082 起不再与它同构：多出
#: ``talk_to``——它带豁免规则但不是自主动作（没有渴望闸门，主人原话是唯一
#: 的门），所以不变式是 ``EXEMPT_TOOLS == SELF_ACTION_TOOLS | {"talk_to"}``。
EXEMPT_TOOLS = frozenset(_EXEMPT_RULES)

#: 超出这个长度的文本只截前一段参与匹配：正则本身有界，截断只是为了不让一次
#: 异常长的粘贴（整篇文档）在这一步多花时间。
_MAX_SCAN = 2000


def explicit_request(user_text: Any, tool: str) -> bool:
    """主人这句原话是否**明确让**她做 ``tool`` 这个动作。

    全函数：``None`` / 空串 / 非字符串 / 未知工具一律 ``False``，任何内部异常
    也吞掉当 ``False``（判断失败就回落到阈值路径，不能让一个正则 bug 掀翻回合）。
    """
    if not isinstance(user_text, str):
        return False
    rules = _EXEMPT_RULES.get(str(tool or "").strip())
    if not rules:
        return False
    text = user_text.strip()[:_MAX_SCAN]
    if not text:
        return False
    text = _NEGATED.sub(" ", text)
    for pattern in rules:
        try:
            if pattern.search(text):
                return True
        except Exception:  # pragma: no cover - defensive, patterns are static
            continue
    return False
