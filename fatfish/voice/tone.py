"""从一句回复里读出一个语气类别（模型没明说时的兜底）。

分两层是有意的：

  * 模型自己说的（`send_voice(emotion=...)`）永远优先 —— 它知道自己想表达
    什么，也读得到上下文，这是最准的那一路；
  * 模型没说的时候（大多数自发语音都走这条路，根本没经过工具调用），就用
    这里的规则兜底。它读的是**鲸鱼娘自己的回复**，因为要决定的是"这句话
    该怎么念"，而不是"用户什么心情"。

判定顺序和门槛都是踩出来的：

  * **负面优先**。遇到"气死我了，不过好开心"这种混合句，保守地当负面 ——
    用错方向的语气，比不用语气难听得多。
  * **但要分清"谁的情绪"**。「被骂了？那一定很难受吧（小声）」是在哄人，
    字面上却有「骂」—— 上线实测里这句被判成 annoyed，于是用非常生气的语气
    去安慰一个刚被骂的人。所以负面词要看它前面是不是被动/受事（被、挨、遭、
    让人、给人）：那是"她/用户受了什么事"，不是"她在生气"。
  * **说话方式优先于话题情绪**。SOFT 那组词是"她怎么开口"（小声、陪你、
    别怕），SAD 那组是"她说到什么"（难受、委屈）。哄人的句子几乎必然
    提到后者，所以 SOFT 必须排在 SAD 前面，否则安慰话会被念成悲伤。
  * **疲倦归慵懒，不归悲伤**。「累死了」如果判成 sad，声音会被压成虚弱；
    鲸鱼娘的累应该是"慵懒地贴着人"，还带着甜。所以疲惫词单独一组（TIRED），
    走 soft 且不改速度。这是产品判断：元气是她的底层底色，任何情绪都不该
    把它抹掉。
  * **场合词不看强度**。"晚安""抱抱"在强度上可能只有 1.7（句子短、没感叹
    号），但该用什么语气是由场合决定的，不是由激动程度决定的。这跟表情包里
    给"晚安/谢谢"设 3.0 地板是同一个道理。
  * **情绪词要过门槛**。"这个公式量纲不对，烦"命中了"烦"，但强度只有 0.8 ——
    那是在嫌公式烦，不是在发脾气。拿生气语气念技术解释会立刻出戏。

低于门槛就是 neutral，也就是"用默认速度、不加任何措辞"，和接 instruct 之前
几乎一样（只差默认速度快 5%）。宁可没有语气，也不要硬塞一个错的 —— 更不要
为了"贴情绪"把她的元气抹掉。
"""

from __future__ import annotations

from .emotion import emotion_intensity
from ..tts.instruct import normalize_tone

# 情绪类的门槛（负向和正向都要过）。和表情包那道闸门同一个刻度 2.0：
# 两处用同一个数字，调一个的时候另一个不会偷偷变得不一致。
# 曾用过 2.2，结果「我有点难过，怎么办啊」正好 2.10 被卡成 neutral —— 差 0.1
# 就丢掉一句该温柔说的台词，不值。
TONE_FLOOR = 2.0
# 到这条线才用「开心 + 尽可能快」那句最强烈的指令。
# 原本定 3.5，按模型的一致性调高了：实测模型把「今天真的好开心！」（3.0）仍
# 判成 happy 而不是 lively —— 也就是说 3.5 太激进，"有点开心"会被念成"兴奋"。
# 兜底规则宁可比模型保守，走错方向的语气比不用语气难听。
LIVELY_FLOOR = 3.8

# 顺序有意义：annoyed > soft > sad > positive。见模块文档。
ANNOYED = (
    "烦", "气死", "生气", "讨厌", "怒", "哼", "不理你", "凶", "骂",
    "受不了", "无语", "离谱", "服了", "笨蛋", "傻瓜", "才不是", "才不理",
)
SAD = (
    "难过", "委屈", "想哭", "哭", "心疼", "低落", "难受", "丧", "emo",
    "郁闷", "崩溃", "焦虑", "紧张", "慌", "怕", "不安",
    "孤单", "寂寞", "疼", "撑不住",
)
# 疲倦不等于悲伤 —— 这是产品判断，不是语言学判断。
# 「累死了」如果走 sad，声音会被压成有气无力的虚弱；鲸鱼娘的疲倦应该是**慵懒**
# （还带着甜、还想贴着人）。所以疲惫类单独一组，归到 soft，速度不变。
TIRED = (
    "累", "疲惫", "困", "乏", "没力气", "不想动", "起不来", "熬夜", "没睡",
    "好倦", "倦了", "昏昏欲睡", "打哈欠",
)
# 场合词：不看强度，命中就用（晚安、抱抱、哄人时的那几句）。
SOFT = (
    "晚安", "早安", "好梦", "抱抱", "贴贴", "摸摸", "亲亲", "想你",
    "撒娇", "轻轻", "小声", "悄悄", "陪你", "关心", "休息", "早点睡",
    "别熬", "注意身体", "没关系", "慢慢来",
    # 哄人时真正会说的话。上线那条真实回复是「先别动了，就靠着歇一会儿」
    # 「我在这儿听着」—— 一句 SAD 词都没有，光靠场合词接不住。
    "别怕", "别动", "歇", "我在这儿", "我陪你", "辛苦了", "不急", "乖",
)
POSITIVE = (
    "开心", "高兴", "好耶", "爽", "得意", "飘", "兴奋", "激动", "幸福",
    "喜欢", "爱你", "夸", "谢谢", "笑",
    # 好事本身：没有情绪形容词，但谁都知道该是什么语气。
    "满分", "考过", "通过", "赢了", "搞定", "成功", "到手", "太好了",
)

# 被动/受事标记：出现在负面词前面时，说的是"谁受了这件事"，不是"谁在生气"。
_PASSIVE = ("被", "挨", "遭", "让人", "给人")


def _hit(text: str, words: tuple[str, ...]) -> bool:
    return any(word in text for word in words)


def _hit_active(text: str, words: tuple[str, ...]) -> bool:
    """命中负面词，且不是被动/受事构造。

    「被骂了」= 她受了委屈，「骂你了」= 她在凶人。同一个"骂"字，语气相反，
    所以必须看它前面两个字。这是上线实测抓到的那条 bug（安慰话被判成生气）。
    """
    for word in words:
        start = 0
        while True:
            idx = text.find(word, start)
            if idx < 0:
                break
            before = text[max(0, idx - 2) : idx]
            if not any(before.endswith(marker) for marker in _PASSIVE):
                return True
            start = idx + len(word)
    return False


def tone_from_text(text: str) -> str:
    """回复文本 → 六个类别之一。"""
    raw = str(text or "")
    if not raw.strip():
        return "neutral"
    strong = emotion_intensity(raw)

    if strong >= TONE_FLOOR and _hit_active(raw, ANNOYED):
        return "annoyed"
    # 疲倦先于悲伤：两者都让人不想说话，但对鲸鱼娘来说一个是"慵懒地贴着人"、
    # 一个是"真的难过"，声音完全不同。实测把她压成 sad 会变成有气无力的虚弱。
    if _hit(raw, TIRED):
        return "soft"
    # 说话方式先于话题情绪，否则「别难过了，抱抱」会被念成悲伤。
    if _hit(raw, SOFT):
        return "soft"
    if strong >= TONE_FLOOR and _hit(raw, SAD):
        return "sad"
    if strong >= TONE_FLOOR and _hit(raw, POSITIVE):
        return "lively" if strong >= LIVELY_FLOOR else "happy"
    return "neutral"


def reply_tone(text: str, explicit: object = None) -> str:
    """模型给了就用模型的，没给才看文本。

    非法值不报错：`normalize_tone` 会把它收成 neutral，等于"没指定" ——
    合成器不该因为模型多打一个字就整条语音失败。
    """
    if explicit is not None and str(explicit).strip():
        return normalize_tone(explicit)
    return tone_from_text(text)
