"""查询侧同义词扩展：给只会字面匹配的 hash 后端补上「换一种说法」的能力。

HashEmbedder 只奖励查询与索引文本的字面重合（``fatfish/memory/embedder.py``
的模块注释自己就承认它是「穿着向量外衣的词面匹配器」）。实测病例：用户说
「真的惊到我了」，库里写的是「惊讶、没想到」，零重合，相似度通道贡献为 0。

做法：把查询里出现的触发词展开成库里的说法，**追加**到查询文本后面再参与
嵌入与关键词匹配。三个边界刻死：

* 只扩查询侧。索引文本一个字不动，调这张表永远不需要重算库；
* 一跳定型。展开只扫原文，别名不当二次触发词（「气死」补「生气」就够了，
  顺着「生气」再补「气鼓鼓」是两跳，不许）；
* 别名已在查询里出现时不重复追加。

触发表照着真实库的 usage_description 用词挑，每条 1-3 个别名；触发词必须
无歧义（「惊」可以，「牛」不行）。新病例实测确认后往表里加一行即可。
"""

from __future__ import annotations

# 触发词 -> 库里实际会出现的说法。
