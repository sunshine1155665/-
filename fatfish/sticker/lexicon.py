def expand_query(text: str) -> str:
    """原文 + 命中触发词的别名，空格拼接。没命中就原样返回。"""
    source = (text or "").strip()
    if not source:
        return source
    lowered = source.lower()
    extras: list[str] = []
    for trigger, aliases in QUERY_ALIASES.items():
        if trigger not in lowered:
            continue
        for alias in aliases:
            if alias not in lowered and alias not in extras:
                extras.append(alias)
    if not extras:
        return source
    return " ".join([source, *extras])
